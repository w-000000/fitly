-- FITLY ERD3 physical schema.
-- The logical USER entity is implemented as app_user because USER is a
-- PostgreSQL keyword. All timestamps are stored as timestamptz/UTC.

create schema if not exists private;
revoke all on schema private from public;

create or replace function private.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

revoke execute on function private.set_updated_at() from public, anon, authenticated, service_role;

