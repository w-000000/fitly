declare
  table_name text;
begin
  foreach table_name in array array[
    'app_user', 'role', 'user_role', 'user_profile', 'style', 'user_preferred_style',
    'business', 'business_member', 'business_contract', 'product',
    'product_description_generation', 'product_variant', 'wardrobe_item',
    'recommendation_request', 'recommendation_request_wardrobe', 'recommendation',
    'outfit_feedback', 'recommendation_item', 'rental_order', 'rental_item',
    'group_rental_detail', 'group_rental_request_item', 'return_process',
    'business_settlement'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format(
      'revoke all on table public.%I from anon, authenticated, service_role',
      table_name
    );
  end loop;
end;
$$;

revoke all on all sequences in schema public from anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  revoke all on tables from anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  revoke all on sequences from anon, authenticated, service_role;
alter default privileges for role postgres in schema public
  revoke execute on functions from public, anon, authenticated, service_role;

insert into public.role (role_name)
values ('CUSTOMER'), ('ENTERPRISE'), ('ADMIN');

insert into public.style (style_name)
values ('Minimal'), ('Formal'), ('Street'), ('Casual');

commit;
